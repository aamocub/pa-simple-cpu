/*
    NOTE: The overview of the CPU core. Each stage is divided in its own module. Each module will have a series of inputs and outputs. For the pipeline registers, it will be its own registers, outside of the module. The semi-finished IF stage is an example of this.
*/

module top
    import pa_pkg::*;
    import riscv_pkg::*;
#(
    parameter DEBUG = 0
) (
    input logic clk_i,
    input logic rst_i
);

    // ----------------------------------------------------------------------------------------------------------------
    // IF Stage
    // ----------------------------------------------------------------------------------------------------------------

    if_stage_t if_out;

    if_stage if_stage (
        .clk_i (clk_i),
        .rst_i (rst_i),
        .ctrl_i(ctrl_i),
        .req_o (req_o),
        .resp_i(resp_i),
        .if_o  (if_out)
    );

    // ----------------------------------------------------------------------------------------------------------------
    // ID Stage
    // ----------------------------------------------------------------------------------------------------------------

    if_stage_t if_id;

    register #(
        .reg_t(if_stage_t)
    ) if_id_pipeline_reg (
        .clk_i  (clk_i),
        .rst_i  (rst_i),
        .en_i   (1),
        .flush_i(0),
        .d_i    (if_out),
        .q_o    (if_id)
    );

    id_stage id_stage (
        .clk_i    (clk_i),
        .rst_i    (rst_i),
        .fetch_i  (if_id),
        .from_wb_i(),
        .decode_o ()
    );

